    public static IReadOnlyList<LanguageOption> Languages { get; } =
    [
        new("en-US", "English"),
        new("vi-VN", "Tiếng Việt")
    ];

    public static string CurrentLanguage { get; private set; } = "en-US";

    public static event EventHandler? LanguageChanged;

    public static IReadOnlyDictionary<string, string> CurrentStrings =>
        CurrentLanguage == "vi-VN" ? Vietnamese : English;

    public static void SetLanguage(string? languageCode)
    {
        var normalized = string.Equals(languageCode, "vi-VN", StringComparison.OrdinalIgnoreCase)
            ? "vi-VN"
            : "en-US";

        CurrentLanguage = normalized;
        var culture = CultureInfo.GetCultureInfo(normalized);
        CultureInfo.CurrentCulture = culture;
        CultureInfo.CurrentUICulture = culture;
        LanguageChanged?.Invoke(null, EventArgs.Empty);
    }

    public static string Get(string key, params object?[] arguments)
    {
        var value = CurrentStrings.TryGetValue(key, out var localized)
            ? localized
            : English.TryGetValue(key, out var fallback)
                ? fallback
                : key;

        return arguments.Length == 0
            ? value
            : string.Format(CultureInfo.CurrentCulture, value, arguments);
    }

    public static string GetDataValue(string? value)
    {
        if (string.IsNullOrWhiteSpace(value))
            return "--";

        var key = value.Replace(" ", string.Empty, StringComparison.Ordinal).ToLowerInvariant() switch
        {
            "nextplay" => "NextPlay",
            "done" => "Done",
            "playing" => "Playing",
            "intended" => "Intended",
            "dropped" => "Dropped",
            "pending" => "Pending",
            "ready" => "Ready",
            "painted" or "pirated" => "Pirated",
            "gamepass" => "GamePass",
            "steamoff" => "SteamOff",
            "playstation" or "psrequired" => "PsRequired",
            "notowned" => "NotOwned",
            _ => string.Empty
        };

        return key.Length == 0 ? value : Get(key);
    }

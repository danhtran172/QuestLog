type I18nValue = {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: string) => string;
};

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  // Mac dinh en-US. Gia tri that se duoc nap tu GET /api/settings khi co backend.
  const [lang, setLangState] = useState<Lang>("en-US");

  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    setApiLanguage(next);
    document.documentElement.lang = next;
    // TODO(backend): PUT /api/settings — ngon ngu thuoc config dung chung voi Tray,
    // KHONG duoc luu localStorage (DOMAIN_RULES §15).
  }, []);

  const t = useCallback(
    (key: string) => STRINGS[lang][key] ?? STRINGS["en-US"][key] ?? key,
    [lang],
  );

  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <I18nContext value={value}>{children}</I18nContext>;
}

export function useI18n(): I18nValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside <I18nProvider>");
  return ctx;
}
